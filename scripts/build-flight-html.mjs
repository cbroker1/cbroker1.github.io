/**
 * Packs the flyable scene into one self-contained HTML file.
 *
 * Everything in it is code: the flight model, the WebGPU renderer and its
 * shaders, the page around them. There are no textures, models, fonts or
 * requests of any kind, so the file runs from disk as it stands.
 *
 * It is built from the same modules the homepage hero uses, starting at
 * `src/flight/standalone.ts`, with Vite doing the bundling (it is already
 * here, under Astro). Vite minifies the JavaScript but leaves strings alone,
 * and the shaders are strings, so those are minified here.
 *
 *   npm run flight:html
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { brotliCompressSync, gzipSync } from 'node:zlib';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const ENTRY = fileURLToPath(new URL('../src/flight/standalone.ts', import.meta.url));
const SHELL = fileURLToPath(new URL('../src/flight/standalone.html', import.meta.url));
const OUT = fileURLToPath(new URL('../public/flight/index.html', import.meta.url));

/** Characters that can run together into a different operator, or a comment. */
const JOINS = /[-+*/<>=!&|%^]/;

/**
 * WGSL with its comments and spare space taken out and its numbers written
 * short (1.0 as 1., 0.5 as .5). Names are left as they are.
 */
export function minifyWgsl(source) {
  const text = source.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/\/\/[^\n]*/g, ' ');
  const tokens =
    text.match(
      /[A-Za-z_][A-Za-z0-9_]*|\d+\.?\d*(?:[eE][+-]?\d+)?[iufh]?|\.\d+(?:[eE][+-]?\d+)?[fh]?|->|==|!=|<=|>=|&&|\|\||\+\+|--|<<|>>|[-+*/%&|^]=|\S/g
    ) ?? [];
  const wordy = (token) => /^[A-Za-z0-9_.]/.test(token) && token !== '.';
  let out = '';
  let before = '';
  for (let token of tokens) {
    if (/^\d+\.\d*$/.test(token)) {
      token = token.replace(/0+$/, '');
      if (token.startsWith('0.') && token.length > 2) token = token.slice(1);
    }
    // Two words need a space between them, and so do two operators that
    // would otherwise read as one.
    if (before && ((wordy(before) && wordy(token)) || (JOINS.test(before.at(-1)) && JOINS.test(token[0])))) out += ' ';
    out += token;
    before = token;
  }
  return out;
}

/** A Vite plugin that minifies every template string marked as WGSL. */
const shaders = {
  name: 'minify-wgsl',
  enforce: 'pre',
  transform(code, id) {
    if (!id.endsWith('.ts') || !code.includes('/* wgsl */')) return null;
    return code.replace(/\/\* wgsl \*\/ `([^`]*)`/g, (_, source) => '`' + minifyWgsl(source) + '`');
  },
};

function minifyCss(css) {
  return css
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\s+/g, ' ')
    .replace(/ ?([{};,]) ?/g, '$1')
    .replace(/: /g, ':')
    .replace(/;}/g, '}')
    .trim();
}

function minifyHtml(html) {
  return html
    .replace(/<style>([\s\S]*?)<\/style>/, (_, css) => `<style>${minifyCss(css)}</style>`)
    .replace(/>\s+</g, '><')
    .trim();
}

export async function buildFlightHtml() {
  // Imported here, not at the top, so that minifyWgsl can be used without it.
  const { build } = await import('vite');
  const result = await build({
    configFile: false,
    root: ROOT,
    logLevel: 'warn',
    plugins: [shaders],
    build: {
      write: false,
      minify: true,
      target: 'esnext',
      modulePreload: false,
      rollupOptions: { input: ENTRY, output: { format: 'es', codeSplitting: false } },
    },
  });
  const chunks = (Array.isArray(result) ? result[0] : result).output.filter((piece) => piece.type === 'chunk');
  if (chunks.length !== 1) throw new Error(`Expected one script, got ${chunks.length}.`);
  // A closing script tag inside the script would end it early.
  const script = chunks[0].code.trim().replace(/<\/script/gi, '<\\/script');
  // A function, so that nothing in the script is taken for a replacement pattern.
  return minifyHtml(readFileSync(SHELL, 'utf8'))
    .replace('<!doctype html>', '<!doctype html><!-- Generated by scripts/build-flight-html.mjs. Do not edit by hand. -->')
    .replace('/*BUNDLE*/', () => script);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const html = await buildFlightHtml();
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, html);
  const bytes = Buffer.byteLength(html);
  const kb = (n) => `${(n / 1024).toFixed(1)} KB`;
  console.log(`Wrote ${OUT}`);
  console.log(`  minified  ${bytes} bytes (${kb(bytes)})`);
  console.log(`  gzip      ${gzipSync(html, { level: 9 }).length} bytes (${kb(gzipSync(html, { level: 9 }).length)})`);
  console.log(`  brotli    ${brotliCompressSync(html).length} bytes (${kb(brotliCompressSync(html).length)})`);
}
